-- Final combined query
with customer_sales as (
SELECT customer_id, sum(sales) as total_sales FROM orders GROUP BY customer_id)

SELECT c.customer_name, cs.total_sales, RANK() OVER(ORDER BY cs.total_sales desc) as sales_rank
FROM customer_sales cs
JOIN customers c
ON cs.customer_id = c.customer_id ORDER BY sales_rank;
/*
Insight: Combines JOIN, CTE, and Window Functions to generate a ranked customer sales report.
