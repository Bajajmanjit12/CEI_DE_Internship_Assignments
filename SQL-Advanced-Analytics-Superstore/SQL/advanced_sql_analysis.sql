-- 3. Calculate total sales for each customer.
WITH customer_sales AS
(
SELECT customer_id, sum(sales) as total_sales FROM orders GROUP BY customer_id
)
SELECT * FROM customer_sales;
/*
Insight: Calculates the total sales generated by every customer.
This forms the foundation for customer segmentation and ranking analysis.
*/

-- 4.Find customers whose total sales are above average.
WITH customer_sales as (
SELECT customer_id, sum(sales) as total_sales FROM orders GROUP BY customer_id
)
SELECT * FROM customer_sales WHERE total_sales > 
( SELECT avg(total_sales) FROM customer_sales);
/*
Insight: Identifies customers whose overall purchases exceed the average customer sales.
These customers represent high-value customers and can be targeted for loyalty programs.
*/

-- 5. Rank all customers based on total sales.
WITH customer_sales as
( SELECT customer_id, sum(sales) as total_sales FROM orders GROUP BY customer_id)
SELECT * , RANK() OVER(ORDER BY total_sales DESC) AS sales_rank
FROM customer_sales;
/*
Insight:  Assigns a sales rank to every customer according to total revenue generated.
Helps identify top-performing customers for business analysis and decision-making.
*/

-- 6. Assign row numbers to each order within a customer.
SELECT order_id, customer_id, sales, ROW_NUMBER() OVER(
PARTITION BY customer_id ORDER BY sales DESC) as row_no FROM orders;
/*
Insight: Numbers every order for each customer based on sales value.
Useful for identifying the highest, second-highest, and subsequent orders of each customer.
*/

-- 7. Display top 3 customers based on total sales. 
